// Rebuild the SVG geometry from the checked-in official source. No runtime map service.
import { readFileSync, writeFileSync } from 'node:fs';
import { URL } from 'node:url';
const source = JSON.parse(readFileSync(new URL('../data/geography/c-premium.json', import.meta.url), 'utf8'));
const width = 600;
const height = 500;
const project = ([lon, lat]) => [lon * Math.PI / 180, -Math.log(Math.tan(Math.PI / 4 + lat * Math.PI / 360))];
const target = source.departments.features.find(({ properties }) => properties.code === '78');
const targetPoints = target.geometry.coordinates.flat().map(project);
const minX = Math.min(...targetPoints.map(([x]) => x));
const maxX = Math.max(...targetPoints.map(([x]) => x));
const minY = Math.min(...targetPoints.map(([, y]) => y));
const maxY = Math.max(...targetPoints.map(([, y]) => y));
const scale = Math.min((width - 150) / (maxX - minX), (height - 110) / (maxY - minY));
const transform = (coordinate) => {
  const [x, y] = project(coordinate);
  return [+(width / 2 + (x - (minX + maxX) / 2) * scale).toFixed(2), +(height / 2 + (y - (minY + maxY) / 2) * scale).toFixed(2)];
};
const paths = source.departments.features.map(({ properties, geometry }) => ({
  code: properties.code, name: properties.nom,
  path: geometry.coordinates.map((ring) => ring.map((coordinate, index) => `${index ? 'L' : 'M'}${transform(coordinate).join(',')}`).join('') + 'Z').join(''),
}));
const output = { boundary: target.geometry.coordinates, width, height, marker: transform(source.addresses.project.geometry.coordinates), coordinates: source.addresses.project.geometry.coordinates, paths };
writeFileSync(new URL('../data/c-premium-location-map.ts', import.meta.url), `// Generated by scripts/generate-location-map.mjs from IGN / Etalab data.\n// Development address: 15 route de Mantes, geocoded by IGN / BAN.\nexport const cPremiumLocationMap = ${JSON.stringify(output, null, 2)} as const;\n`);
